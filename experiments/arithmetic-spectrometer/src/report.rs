//! # Report Generator
//!
//! Outputs results in multiple formats:
//! - Markdown report (human-readable, for docs)
//! - JSON data (machine-readable, for further analysis)
//! - Spectral Lift Grid (the π^n/ζ(k) matrix)

use crate::constants::PhysicalTarget;
use crate::engine::{Correction, Match, Tier};
use crate::formulas::ZetaConstants;
use serde::Serialize;
use std::f64::consts::PI;
use std::fmt::Write;

/// Generate the full markdown report.
pub fn generate_markdown(
    matches: &[Match],
    corrections: &[Correction],
    targets: &[PhysicalTarget],
    formula_count: usize,
) -> String {
    let mut report = String::new();

    // Header
    writeln!(report, "# Arithmetic Mass Spectrometer: Complete Results\n").unwrap();
    writeln!(report, "**Generated:** {}", chrono::Local::now().format("%Y-%m-%d %H:%M:%S %Z")).unwrap();
    writeln!(report, "**Formula library:** {} entries", formula_count).unwrap();
    writeln!(report, "**Targets:** {} physical constants", targets.len()).unwrap();
    writeln!(report, "**Total comparisons:** {}", formula_count * targets.len()).unwrap();
    writeln!(report, "**Matches (< 2%):** {}", matches.len()).unwrap();
    writeln!(report, "**Auto-corrections found:** {}\n", corrections.len()).unwrap();

    // Disclaimer
    writeln!(report, "> **DISCLAIMER:** This is exploratory pattern-matching, not physics").unwrap();
    writeln!(report, "> derivation. The formulas found are numerical coincidences until a").unwrap();
    writeln!(report, "> causal mechanism is established. The 6π⁵ approximation (Lenz, 1951)").unwrap();
    writeln!(report, "> is a known numerological near-miss.\n").unwrap();
    writeln!(report, "---\n").unwrap();

    // Top 30
    writeln!(report, "## Top 30 Matches\n").unwrap();
    writeln!(report, "| Rank | Target | Formula | Value | Actual | Error | Tier |").unwrap();
    writeln!(report, "|---|---|---|---|---|---|---|").unwrap();
    for (i, m) in matches.iter().take(30).enumerate() {
        writeln!(report, "| {} | {} | {} | {:.6} | {:.6} | {:.6}% | {} |",
            i + 1, m.target_symbol, m.formula_name, m.formula_value,
            m.target_value, m.error_pct, m.tier).unwrap();
    }

    // Auto-corrections
    if !corrections.is_empty() {
        writeln!(report, "\n## Auto-Corrected Formulas\n").unwrap();
        writeln!(report, "Near-misses improved by α-based perturbative corrections:\n").unwrap();
        writeln!(report, "| Target | Corrected Formula | Value | Actual | New Error | Was | Improvement |").unwrap();
        writeln!(report, "|---|---|---|---|---|---|---|").unwrap();
        for c in corrections.iter().take(30) {
            writeln!(report, "| {} | {} | {:.6} | {:.6} | {:.6}% | {:.4}% | {:.0}× |",
                c.target_symbol, c.corrected_formula, c.corrected_value,
                c.target_value, c.new_error_pct, c.old_error_pct,
                c.improvement_factor).unwrap();
        }
    }

    // Spectral Lift Grid
    writeln!(report, "\n{}", generate_spectral_grid(targets)).unwrap();

    // By category
    let categories: Vec<String> = {
        let mut cats: Vec<String> = matches.iter().map(|m| m.target_category.clone()).collect();
        cats.sort();
        cats.dedup();
        cats
    };

    for cat in &categories {
        let cat_matches: Vec<&Match> = matches.iter()
            .filter(|m| &m.target_category == cat)
            .collect();
        if cat_matches.is_empty() { continue; }

        writeln!(report, "\n## {} Matches\n", cat).unwrap();
        writeln!(report, "| Target | Formula | Value | Actual | Error | Tier |").unwrap();
        writeln!(report, "|---|---|---|---|---|---|").unwrap();
        for m in cat_matches.iter().take(20) {
            writeln!(report, "| {} | {} | {:.6} | {:.6} | {:.6}% | {} |",
                m.target_symbol, m.formula_name, m.formula_value,
                m.target_value, m.error_pct, m.tier).unwrap();
        }
    }

    // S-Duality summary
    writeln!(report, "\n---\n").unwrap();
    writeln!(report, "## The S-Duality Mass Table\n").unwrap();
    writeln!(report, "Confirmed formulas from the S-Duality framework:\n").unwrap();
    writeln!(report, "| Quantity | Bare Formula | Corrected | Error |").unwrap();
    writeln!(report, "|---|---|---|---|").unwrap();
    writeln!(report, "| m_p/m_e | 6π⁵ = π⁷/ζ(2) | 6π⁵·(1+α²/3) | **0.00011%** |").unwrap();
    writeln!(report, "| (m_n-m_p)/m_e | 5/2 = ζ(2)²/ζ(4) | (5/2)·(1+α·ζ(2)) | **0.039%** |").unwrap();
    writeln!(report, "| sin²θ_W | 1/(4·ζ(4)) = 22.5/π⁴ | — | **0.098%** |").unwrap();
    writeln!(report, "| m_b/m_c | 2·ζ(2) = π²/3 | — | **0.044%** |").unwrap();
    writeln!(report, "| Q_K (Koide) | 2/3 | — | **0.00085%** |").unwrap();

    writeln!(report, "\n---\n").unwrap();
    writeln!(report, "*Generated by the Arithmetic Mass Spectrometer* 🪞❄️\n").unwrap();

    report
}

/// Generate the Spectral Lift Grid: π^n / ζ(k) matrix.
pub fn generate_spectral_grid(targets: &[PhysicalTarget]) -> String {
    let c = ZetaConstants::new();
    let mut grid = String::new();

    writeln!(grid, "## Spectral Lift Grid: π^n / ζ(k)\n").unwrap();
    writeln!(grid, "Each cell shows π^n/ζ(k). Bold entries match a physical constant.\n").unwrap();

    // Header
    write!(grid, "| n |").unwrap();
    for &(k, _, _) in &c.zetas[..5] {
        write!(grid, " ζ({}) |", k).unwrap();
    }
    writeln!(grid).unwrap();
    write!(grid, "|---|").unwrap();
    for _ in 0..5 { write!(grid, "---|").unwrap(); }
    writeln!(grid).unwrap();

    for n in 1..=10 {
        write!(grid, "| π^{} |", n).unwrap();
        for &(_, zk, _) in &c.zetas[..5] {
            let val = PI.powi(n) / zk;
            // Find best match
            let mut best = ("", 100.0_f64);
            for t in targets {
                let err = ((val / t.value) - 1.0).abs() * 100.0;
                if err < best.1 { best = (t.symbol, err); }
            }
            if best.1 < 0.1 {
                write!(grid, " **{:.1}** ≈{} ⭐ |", val, best.0).unwrap();
            } else if best.1 < 1.0 {
                write!(grid, " {:.1} ≈{} |", val, best.0).unwrap();
            } else {
                write!(grid, " {:.1} |", val).unwrap();
            }
        }
        writeln!(grid).unwrap();
    }
    grid
}

/// Generate JSON output for machine consumption.
pub fn generate_json(
    matches: &[Match],
    corrections: &[Correction],
) -> String {
    #[derive(Serialize)]
    struct Output<'a> {
        matches: &'a [Match],
        corrections: &'a [Correction],
    }
    serde_json::to_string_pretty(&Output { matches, corrections })
        .unwrap_or_else(|e| format!("{{\"error\": \"{}\"}}", e))
}

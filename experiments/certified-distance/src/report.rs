//! Report generation and Lean export from certificates.

use crate::certify::Certificate;
use std::path::Path;

/// Generate a human-readable report from all certificates in a directory.
pub fn generate_report(cert_dir: &str) {
    let certs = load_certificates(cert_dir);

    if certs.is_empty() {
        println!("  No certificates found in {}/", cert_dir);
        return;
    }

    println!();
    println!("  ╔══════════════════════════════════════════════════════════════════╗");
    println!("  ║  🏛️  CATHEDRAL CERTIFIED DISTANCE REPORT                        ║");
    println!("  ╚══════════════════════════════════════════════════════════════════╝");
    println!();
    println!("  {} certificates loaded from {}/", certs.len(), cert_dir);
    println!();

    // Table header
    println!("  {:>8} {:>16} {:>12} {:>12} {:>12} {:>8}",
        "N", "d²_N", "λ_min", "κ(G)", "Δd²", "method");
    println!("  {} {} {} {} {} {}",
        "─".repeat(8), "─".repeat(16), "─".repeat(12),
        "─".repeat(12), "─".repeat(12), "─".repeat(8));

    let mut prev_d_sq: Option<f64> = None;
    for cert in &certs {
        let delta = prev_d_sq.map(|p| p - cert.distance.d_sq);
        let lambda_min = cert.spectrum.as_ref()
            .map(|s| format!("{:.4e}", s.lambda_min))
            .unwrap_or_else(|| "—".to_string());
        let cond = cert.spectrum.as_ref()
            .map(|s| format!("{:.2e}", s.condition_number))
            .unwrap_or_else(|| "—".to_string());
        let delta_str = delta
            .map(|d| format!("{:.4e}", d))
            .unwrap_or_else(|| "—".to_string());
        let method = cert.distance.method
            .replace("GPU_Cholesky_f64", "GPU")
            .replace("CPU_Cholesky_nalgebra", "CPU")
            .replace("GPU_DD_Cholesky_31digit", "DD")
            .replace("GPU_QS_Cholesky_28digit", "QS");

        println!("  {:>8} {:>16.12} {:>12} {:>12} {:>12} {:>8}",
            cert.max_n, cert.distance.d_sq, lambda_min, cond, delta_str, method);

        prev_d_sq = Some(cert.distance.d_sq);
    }

    println!();

    // Summary statistics
    let d_min = certs.iter().map(|c| c.distance.d_sq).fold(f64::MAX, f64::min);
    let d_max = certs.iter().map(|c| c.distance.d_sq).fold(0.0f64, f64::max);
    let all_monotone = certs.windows(2).all(|w| w[1].distance.d_sq <= w[0].distance.d_sq);
    let all_positive = certs.iter().all(|c| {
        c.spectrum.as_ref().map_or(true, |s| s.lambda_min_positive)
    });

    println!("  Summary:");
    println!("    d² range: [{:.12}, {:.12}]", d_min, d_max);
    println!("    Monotonically decreasing: {}", if all_monotone { "✓ YES" } else { "✗ NO" });
    println!("    All λ_min > 0: {}", if all_positive { "✓ YES" } else { "✗ NO" });
    println!();
}

/// Generate a Lean file with axioms from certificates.
pub fn lean_export(cert_dir: &str) {
    let certs = load_certificates(cert_dir);

    if certs.is_empty() {
        println!("  No certificates found.");
        return;
    }

    let output_path = format!("{}/CertifiedBounds.lean", cert_dir);

    let mut lean = String::new();
    lean.push_str("/-!\n");
    lean.push_str("  # Certified Distance Bounds (Auto-Generated)\n");
    lean.push_str("  \n");
    lean.push_str("  Generated by: certified-distance v1.0.0\n");
    lean.push_str(&format!("  Certificates: {}\n", certs.len()));
    lean.push_str("  \n");
    lean.push_str("  Each bound is backed by a JSON certificate with:\n");
    lean.push_str("  - Matrix SHA-256 checksums\n");
    lean.push_str("  - Multi-tier computation verification\n");
    lean.push_str("  - Spectral analysis (λ_min > 0)\n");
    lean.push_str("-/\n\n");
    lean.push_str("import Cathedral.Defs\n\n");
    lean.push_str("namespace Cathedral.CertifiedComputation\n\n");

    for cert in &certs {
        let bound = (cert.distance.d_sq * 10000.0).ceil() / 10000.0;
        lean.push_str(&format!("-- Certificate: cert_N{}.json\n", cert.max_n));
        lean.push_str(&format!("-- d²_{} = {:.15} ({})\n",
            cert.max_n, cert.distance.d_sq, cert.distance.method));
        lean.push_str(&format!("axiom certified_d_sq_{} : nbDistSq' {} < {:.4}\n\n",
            cert.max_n, cert.max_n, bound));

        if let Some(ref s) = cert.spectrum {
            if s.lambda_min_positive {
                lean.push_str(&format!("-- λ_min = {:.6e}\n", s.lambda_min));
                lean.push_str(&format!("axiom certified_lambda_min_{} : 0 < lambdaMin {}\n\n",
                    cert.max_n, cert.max_n));
            }
        }
    }

    lean.push_str("end Cathedral.CertifiedComputation\n");

    std::fs::write(&output_path, &lean).expect("Failed to write Lean file");
    println!("  📝 Lean file → {} ({} axioms)", output_path, certs.len() * 2);
}

/// Verify a single certificate by re-checking internal consistency.
pub fn verify_certificate(path: &str) {
    let content = std::fs::read_to_string(path).expect("Failed to read certificate");
    let cert: Certificate = serde_json::from_str(&content).expect("Invalid certificate JSON");

    println!();
    println!("  Verifying: {}", path);
    println!("  N = {}, dim = {}", cert.max_n, cert.dim);
    println!("  d² = {:.15}", cert.distance.d_sq);

    let mut ok = true;

    // Check d² is in valid range
    if cert.distance.d_sq < 0.0 || cert.distance.d_sq > 1.0 {
        println!("  ✗ d² out of range [0, 1]");
        ok = false;
    } else {
        println!("  ✓ d² ∈ [0, 1]");
    }

    // Check dim = N - 1
    if cert.dim != cert.max_n - 1 {
        println!("  ✗ dim ≠ N - 1");
        ok = false;
    } else {
        println!("  ✓ dim = N - 1");
    }

    // Check spectral positivity
    if let Some(ref s) = cert.spectrum {
        if s.lambda_min > 0.0 {
            println!("  ✓ λ_min = {:.6e} > 0", s.lambda_min);
        } else {
            println!("  ✗ λ_min = {:.6e} ≤ 0", s.lambda_min);
            ok = false;
        }
    }

    // Check monotonicity
    if let Some(ref m) = cert.monotonicity {
        if m.strictly_decreased {
            println!("  ✓ d²_{} < d²_{} (Δ = {:.6e})", cert.max_n, m.previous_n, m.decrease_amount);
        } else {
            println!("  ✗ Monotonicity violation!");
            ok = false;
        }
    }

    // Check cross-validation
    if let Some(ref cc) = cert.distance.cross_check {
        println!("  ✓ Cross-check: {} digits agree ({})", cc.agreement_digits, cc.method);
    }

    println!();
    if ok {
        println!("  ✅ Certificate VALID");
    } else {
        println!("  ❌ Certificate has ISSUES");
    }
    println!();
}


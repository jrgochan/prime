/// Get the first `n` zeros (clamped to available count).
pub fn first_n(n: usize) -> &'static [f64] {
    &ZEROS[..n.min(ZERO_COUNT)]
}

/// Get zero γₙ by 1-based index (returns None if out of range).
pub fn gamma(n: usize) -> Option<f64> {
    if n >= 1 && n <= ZERO_COUNT {
        Some(ZEROS[n - 1])
    } else {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn first_zero_is_correct() {
        assert!((ZEROS[0] - 14.134725141734694).abs() < 1e-12);
    }

    #[test]
    fn hundredth_zero() {
        // γ₁₀₀ ≈ 233.693
        assert!((ZEROS[99] - 233.693).abs() < 0.01);
    }

    #[test]
    fn zeros_are_increasing() {
        for i in 1..ZERO_COUNT {
            assert!(ZEROS[i] > ZEROS[i - 1], "γ_{} should be > γ_{}", i + 1, i);
        }
    }

    #[test]
    fn first_n_clamps() {
        assert_eq!(first_n(5).len(), 5);
        assert_eq!(first_n(999).len(), ZERO_COUNT);
    }
}
